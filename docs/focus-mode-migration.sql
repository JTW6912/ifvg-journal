-- 看图模式的右侧/底部要额外显示哪些字段。数组，元素是字段 id。
--
-- 为什么不跟卡片视图共用 card_fields：两个模式想看的东西不一样。
-- 卡片是缩略图墙、一屏几十张，字段多了就糊；看图模式一屏一笔、右边有整栏空间，
-- 正好把 notes / post_note 这种长文本挂上去。共用一份的话，改一边另一边就被连累。
--
-- ⚠ 刻意不给 default：null = 从没配过，前端按内置默认渲染（app.js defaultFocusFields()，
--    默认是所有长文本字段）；空数组 [] = 用户自己按了「清空额外字段」，就该一个都不显示。
--    给了 default '[]' 的话这两件事就没法区分，「清空」按下去会被当成没配过、下次刷新又变回默认。
alter table journal_schema add column if not exists focus_fields jsonb;

-- RLS 不用动：journal_schema 原有的策略照旧生效（自己读写自己的 + admin 只读）。
